"""Can it choose its own goal, instead of being handed one?

THE STEP THIS IS, AND WHY IT IS THE HARD ONE. goal.py showed the system can
pursue a preferred state with no reward. goal_persist.py showed the goal
survives interruption. In both, the goal was HANDED to it: a human picked
the cell. A real want is one the system holds ON ITS OWN. That is the line
between navigating to a target someone set and actually wanting something.

WHERE A GOAL COMES FROM IF NOBODY ASSIGNS IT. In living things, goals come
from NEEDS. You want food because hunger is an internal state your body is
built to reduce. The goal is not arbitrary and it is not given; it is
GENERATED by a condition inside you. Reduce the condition and the goal
dissolves until the condition returns.

So a self-chosen goal needs three things this file builds:

  1. AN INTERNAL NEED that drifts out of balance over time on its own. Here
     it is a single scalar that rises every step. Nobody sets it; it is a
     fact of being this agent.

  2. SOMETHING IN THE WORLD THAT RESOLVES IT. Resource cells. Stepping on
     one drops the need. The agent is NOT told where they are or that they
     matter. It only has its world model and its own rising need.

  3. THE AGENT FORMING THE GOAL ITSELF. When the need is high enough, the
     agent must, from its own state, decide that reaching a resource is
     what it wants, and plan there. Nothing rewards it for this. The need
     is not a reward signal fed to a learner; it is a condition the agent
     resolves by choosing, using the planner from goal.py, to go somewhere
     it was never told to go.

HOW IT PICKS THE GOAL WITHOUT BEING TOLD. It knows the world model. It holds
a belief about where resources are, learned by having stepped on them while
wandering. When its need crosses a threshold, it sets its goal to the
nearest believed resource and plans there. The goal is INTERNALLY
GENERATED: produced by the need plus the model, not handed in.

THE ARMS, so "it chose its goal" cannot be mistaken for something cheaper:

  needy       the full thing: an internal need, a learned belief about
              where resources are, and a goal formed from them when the
              need is high. Chooses its own goal.
  oblivious   has the same need but NEVER forms a goal: moves at random.
              The floor. Its need runs away. This is what no goal looks
              like.
  told        a control that IS handed the nearest resource as a goal by
              the harness, the goal.py style. The ceiling: how well it
              would do if a human pointed at the resource every time. If
              `needy` approaches `told`, choosing the goal itself was
              nearly as good as being told.

THE MEASUREMENT IS THE NEED ITSELF. Not "did it reach a cell" but "did it
keep its own need low over a long life". A system that forms good goals
from its need keeps the need bounded; one that cannot lets it climb. Mean
need over the life is the number, lower is better, and it is the honest
measure because it is the thing the agent is actually trying to manage, not
a target we imposed.

  needy near told, both far below oblivious
      IT CHOSE ITS OWN GOALS AND THEY WORKED. The agent generated goals
      from an internal need and managed that need nearly as well as if it
      had been told where to go. The first self-chosen want in the project.
  needy near oblivious
      Forming the goal from its own belief failed: either the belief about
      where resources are is too poor, or threshold/replanning is wrong.
      A real negative about self-chosen goals, not about goals in general.

    python goal_own.py --world spiral
    python goal_own.py --world wall --steps 3000
"""

import argparse
import random
import statistics
import sys
import os

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from goal import (World, learn_world, model_accuracy, plan_action,  # noqa
                  dist, ACTIONS, SIZE)


NEED_RISE = 0.02          # per step, the need drifts up on its own
NEED_DROP = 0.60          # stepping on a resource drops it by this
NEED_THRESHOLD = 0.35     # above this, the agent forms a goal to resolve it
N_RESOURCES = 1


def place_resources(world, seed):
    rng = random.Random(seed + 500)
    free = world.free()
    return set(rng.sample(free, min(N_RESOURCES, len(free))))


def run_life(world, model, resources, mode, start, horizon, rng,
             steps=1500):
    """One life. The need rises every step; a resource drops it. Returns the
    mean need over the life, which is what the agent is actually managing.

      needy       forms its own goal from its need and its belief about
                  where resources are.
      oblivious   same need, never forms a goal, moves at random.
      told        handed the nearest true resource as a goal.
    """
    pos = start
    need = 0.0
    total = 0.0

    # The agent's BELIEF about where resources are. It starts empty and is
    # filled by actually stepping on them while living. This is the part
    # that makes the goal self-chosen: it is planned toward what the agent
    # has itself discovered, not toward ground truth.
    believed = set()

    for t in range(steps):
        need = min(1.0, need + NEED_RISE)

        if pos in resources:
            need = max(0.0, need - NEED_DROP)
            believed.add(pos)            # learned: a resource is here

        total += need

        if mode == "oblivious":
            a = rng.choice(ACTIONS)

        elif mode == "told":
            # handed the nearest TRUE resource when the need is high
            if need > NEED_THRESHOLD and resources:
                goal = min(resources, key=lambda r: dist(pos, r))
                a = plan_action(pos, goal, model.predict, horizon, rng)
            else:
                a = rng.choice(ACTIONS)

        else:   # needy: choose its own goal
            # Only acts on the need when it is high enough to matter, which
            # is itself a decision: a low need does not command behaviour.
            if need > NEED_THRESHOLD and believed:
                goal = min(believed, key=lambda r: dist(pos, r))
                a = plan_action(pos, goal, model.predict, horizon, rng)
            elif need > NEED_THRESHOLD:
                # need is high but it has never found a resource: explore,
                # because a goal cannot be formed toward the unknown
                a = rng.choice(ACTIONS)
            else:
                # need is low: no goal. wander. the want is absent until the
                # need calls it up, which is what a need-driven goal means
                a = rng.choice(ACTIONS)

        pos = world.step(pos, a)

    return total / steps


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--learn", type=int, default=6000)
    ap.add_argument("--horizon", type=int, default=12)
    ap.add_argument("--steps", type=int, default=1500)
    ap.add_argument("--lives", type=int, default=20)
    ap.add_argument("--seeds", type=int, default=3)
    ap.add_argument("--world", choices=["wall", "spiral"], default="spiral")
    args = ap.parse_args()

    print(f"  a 7x7 grid, world={args.world!r}, {N_RESOURCES} resources it "
          f"is NOT told about")
    print(f"  an internal need rises {NEED_RISE}/step and a resource drops "
          f"it {NEED_DROP}")
    print(f"  nobody assigns a goal; 'needy' must form one from its need "
          f"and what it has found")
    print(f"  the score is MEAN NEED over the life, lower is better, "
          f"because that is what")
    print(f"  the agent is actually trying to manage\n")

    arms = ["needy", "told", "oblivious"]
    needs = {a: [] for a in arms}
    accs = []

    for seed in range(args.seeds):
        world = World(seed, kind=args.world)
        model = learn_world(world, args.learn, seed)
        accs.append(model_accuracy(world, model))
        resources = place_resources(world, seed)
        print(f"  seed {seed}: model {accs[-1]:.0f}% accurate, "
              f"{len(resources)} resources placed", flush=True)

        rng = random.Random(seed + 300)
        free = world.free()
        for _ in range(args.lives):
            start = rng.choice(free)
            for arm in arms:
                mn = run_life(world, model, resources, arm, start,
                              args.horizon, rng, steps=args.steps)
                needs[arm].append(mn)

    print("\n" + "=" * 66)
    print("DID IT CHOOSE ITS OWN GOALS, AND DID THEY WORK?")
    print("=" * 66)
    print(f"  model accuracy {statistics.mean(accs):.0f}%\n")
    print(f"  {'arm':>10} {'mean need':>11}   {'(lower is better)':>18}")
    print("-" * 66)
    m = {}
    for arm in arms:
        m[arm] = statistics.mean(needs[arm])
        note = {"needy": "chose its own goals from the need",
                "told": "handed the nearest resource (ceiling)",
                "oblivious": "never formed a goal (floor)"}[arm]
        print(f"  {arm:>10} {m[arm]:>11.3f}   {note}")

    print("\n" + "=" * 66)
    print("WHAT IT SAYS")
    print("=" * 66)

    span = m["oblivious"] - m["told"]
    if span <= 0.02:
        print(f"  INCONCLUSIVE: being told barely beat random "
              f"({m['told']:.3f} vs {m['oblivious']:.3f}),")
        print(f"  so the world does not reward goal-seeking enough to "
              f"measure choosing one.")
        print(f"  Raise NEED_RISE or lower N_RESOURCES so managing the "
              f"need actually matters.")
        return

    recovered = (m["oblivious"] - m["needy"]) / span
    if recovered > 0.6:
        print(f"  IT CHOSE ITS OWN GOALS AND THEY WORKED. With no goal "
              f"ever assigned, the")
        print(f"  agent kept its own need at {m['needy']:.3f}, against "
              f"{m['oblivious']:.3f} for one that never")
        print(f"  forms a goal and {m['told']:.3f} for one handed the "
              f"resource every time. It closed")
        print(f"  {100 * recovered:.0f}% of the gap to being told, using "
              f"only its own rising need and a")
        print(f"  belief about the world it built by living in it.")
        print(f"\n  This is a self-chosen want: a goal generated from an "
              f"internal condition,")
        print(f"  not handed in. The closest thing in the project to "
              f"wanting something.")
    elif recovered > 0.25:
        print(f"  PARTIAL. The agent's own goals recovered "
              f"{100 * recovered:.0f}% of the gap to being told")
        print(f"  ({m['needy']:.3f} against {m['told']:.3f} told, "
              f"{m['oblivious']:.3f} oblivious). It forms useful goals from "
              f"its need")
        print(f"  but not as well as being pointed at the resource. The "
              f"likely gap is its")
        print(f"  BELIEF about where resources are, which it learns only "
              f"by stepping on them.")
    else:
        print(f"  CHOOSING THE GOAL FAILED. needy ({m['needy']:.3f}) was "
              f"little better than")
        print(f"  oblivious ({m['oblivious']:.3f}). Forming a goal from its "
              f"own belief did not manage")
        print(f"  the need. Most likely the belief is too sparse, because "
              f"it only learns a")
        print(f"  resource's location by landing on it. A real negative "
              f"about self-chosen")
        print(f"  goals on this world, and the thing to fix is how the "
              f"agent comes to believe")
        print(f"  where resources are.")

    print(f"\n  The need is internal and rises on its own. Nothing rewards "
          f"resolving it. The")
    print(f"  goal, when there is one, is produced by the agent from its "
          f"need and its own")
    print(f"  map, which is what makes it the agent's goal rather than "
          f"ours.")


if __name__ == "__main__":
    main()
